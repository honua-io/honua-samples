// Fetches, integrity-verifies, and stages honua-sdk-js's published browser
// sample bundles so scripts/build-gallery.mjs can embed the *actual running
// app* on a gallery detail page (honua-io/honua-samples#11, consuming
// honua-io/honua-sdk-js#642/#648's `sample-bundles-latest` GitHub Release).
//
// Contract consumed (honua-sdk-js's samples/contract/v2/schemas/sample-bundles.schema.json,
// format "honua.sdk.sample-bundles.v2"): a manifest JSON asset
// (sample-bundles.v2.json) listing, per included sample id, its entrypoint,
// dataMode, configDefaults, builtFrom {commit, packageVersion}, and a
// `files[]` array of {path, bytes, sha256, integrity, mediaType} -- plus a
// tarball asset (sample-bundles.tar.gz) containing `<id>/<file.path>` for
// every listed file. Both assets are published on the release tagged
// `sample-bundles-latest` (a rolling tag re-pointed at the latest trunk push
// that built successfully).
//
// HONESTY RULES (see honua-io/honua-samples#11):
//   - Every file extracted from the tarball is SHA-256-verified against the
//     manifest before it is staged anywhere the gallery can serve it. Any
//     mismatch throws -- this is a hard failure, not a warning, and is meant
//     to fail whatever CI step called it (see .github/workflows/pages.yml).
//   - A manifest/tarball *fetch* failure (network blip, release missing, rate
//     limit) is NOT a hard failure: it degrades to the committed snapshot
//     fallback (config/sample-bundles.snapshot.json) recording the last
//     manifest a live fetch actually succeeded for. Since bundle *bytes* are
//     never committed (they're ~8MB+ of built JS/CSS/wasm, regenerated by
//     honua-sdk-js's own CI), a snapshot fallback can only ever restore
//     manifest metadata, never staged files -- so degraded mode always
//     means "no runnable build this deploy", never a stale-but-unverified
//     embed. scripts/build-gallery.mjs is expected to render every sdk-js
//     card as "no runnable build published yet" whenever `degraded` is true,
//     and to show a visible footer notice explaining why.
//
// Zero npm dependencies (matches the rest of this repo's scripts/): uses the
// platform `fetch`, node:crypto, and the system `tar` binary (present on
// every GitHub Actions ubuntu runner and any dev machine likely to have git).
//
// CLI usage (used as a dedicated pages.yml step, run before the gallery
// build so an integrity failure is attributed to its own CI step):
//   node scripts/lib/sample-bundles.mjs
// Without MIN_RUNNABLE_BUNDLES, exits 1 only on integrity mismatch or a
// malformed manifest and degrades on a plain fetch failure. Production sets
// a minimum, making an empty/degraded staging result fail closed.
//
// scripts/build-gallery.mjs calls ensureSampleBundlesStaged() itself too
// (with forceRefetch left false), so a bare `node scripts/build-gallery.mjs`
// with no prior staging step still works end to end for local development --
// it just performs the fetch/verify/stage inline instead of re-reading a
// status file a separate step already wrote.

import { execFileSync, execSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..", "..");

export const SDKJS_REPO = "honua-io/honua-sdk-js";
export const RELEASE_TAG = "sample-bundles-latest";

const RELEASE_BASE_URL = `https://github.com/${SDKJS_REPO}/releases/download/${RELEASE_TAG}`;

export const DEFAULT_MANIFEST_URL = `${RELEASE_BASE_URL}/sample-bundles.v2.json`;
export const DEFAULT_TARBALL_URL = `${RELEASE_BASE_URL}/sample-bundles.tar.gz`;
export const DEFAULT_SNAPSHOT_PATH = path.join(REPO_ROOT, "config", "sample-bundles.snapshot.json");
export const DEFAULT_STAGING_ROOT = path.join(REPO_ROOT, ".sample-bundles-staging");
export const DEFAULT_LOCAL_SDKJS_ROOT = path.join(REPO_ROOT, "..", "honua-sdk-js");
const DEFAULT_LOCAL_SAMPLE_IDS =
  "mcp-gis-assistant,spatial-analytics-workbench,edit-workflow-demo,geocoding-quickstart,oauth-signin,maplibre-quickstart,service-explorer,realtime-incident-dashboard,pmtiles-static,nl-map-control,imagery-cog-quickstart,kepler-analytics,app-bootstrap-basic,geoprocessing-job-runner,runtime-parity-showcase,storytelling-25d-map,terrain-rgb-elevation,unified-ops-workspace,web-components-basic,planning-permitting-workbench";

const EXPECTED_FORMAT = "honua.sdk.sample-bundles.v2";
const EXPECTED_SCHEMA_VERSION = 2;

/**
 * Fetches, integrity-verifies, and stages honua-sdk-js's published sample
 * bundles. Idempotent within a single staging root: if a prior call in this
 * same working tree already wrote a status file and `forceRefetch` isn't
 * set, that cached result is returned without touching the network again
 * (so a dedicated pages.yml staging step followed by build-gallery.mjs's own
 * call don't double-fetch).
 *
 * @returns {Promise<StageResult>}
 * @typedef {object} StageResult
 * @property {"live"|"snapshot"|"none"} source
 * @property {boolean} degraded -- true whenever no verified bundle files are staged this run
 * @property {string|null} degradedReason -- human-readable reason, only set when degraded
 * @property {object|null} manifest -- the honua.sdk.sample-bundles.v2 manifest (or null if none has ever been fetched)
 * @property {string[]} stagedIds -- sample ids with verified files under stagingRoot/<id>/
 * @property {string} stagingRoot
 */
export async function ensureSampleBundlesStaged({
  manifestUrl = process.env.SAMPLE_BUNDLES_MANIFEST_URL?.trim() || DEFAULT_MANIFEST_URL,
  tarballUrl = process.env.SAMPLE_BUNDLES_TARBALL_URL?.trim() || DEFAULT_TARBALL_URL,
  snapshotPath = DEFAULT_SNAPSHOT_PATH,
  stagingRoot = DEFAULT_STAGING_ROOT,
  localSdkJsRoot = process.env.SAMPLE_BUNDLES_LOCAL_SDKJS_ROOT?.trim() || DEFAULT_LOCAL_SDKJS_ROOT,
  localSampleIds = process.env.SAMPLE_BUNDLES_LOCAL_SAMPLE_IDS?.trim() || DEFAULT_LOCAL_SAMPLE_IDS,
  refreshSnapshot = true,
  forceRefetch = false,
  minimumBundles = parseMinimumBundles(process.env.MIN_RUNNABLE_BUNDLES),
} = {}) {
  const statusPath = path.join(stagingRoot, "status.json");
  const localSdkRootAvailable = await canUseLocalSdkJsRoot(localSdkJsRoot);

  if (!forceRefetch) {
    const cached = await readCachedStatus(statusPath);
    if (cached) {
      assertMinimumBundles(cached, minimumBundles);
      return cached;
    }
  }

  let manifest;
  try {
    manifest = await fetchManifest(manifestUrl);
  } catch (err) {
    const result = await finalizeDegraded({
      stagingRoot,
      statusPath,
      snapshotPath,
      reason: `manifest fetch failed (${err.message}) -- falling back to the committed snapshot`,
    });
    assertMinimumBundles(result, minimumBundles);
    return result;
  }

  let tarballBytes;
  try {
    tarballBytes = await fetchBytes(tarballUrl);
  } catch (err) {
    const result = await finalizeDegraded({
      stagingRoot,
      statusPath,
      snapshotPath,
      reason: `tarball fetch failed (${err.message}) -- falling back to the committed snapshot`,
    });
    assertMinimumBundles(result, minimumBundles);
    return result;
  }

  // Integrity mismatches below are NOT caught -- they must propagate and
  // fail whatever process called this (the pages.yml staging step, or a
  // local/CI build-gallery.mjs run). See the file header's honesty rules.
  const stagedIds = await verifyAndStage({ manifest, tarballBytes, stagingRoot });
  const snapshotManifest = manifest;

  const localEntries = await collectLocalSampleManifestEntries({
    localRoot: localSdkRootAvailable,
    explicitIds: localSampleIds,
    liveManifest: manifest,
  });
  const localStagedIds = await stageLocalBundles(localEntries, stagingRoot);
  const localEntriesById = new Map(localEntries.map((entry) => [entry.manifest.id, entry]));
  const manifestAdditions = localEntries
    .filter((entry) => !manifest.samples.some((sample) => sample.id === entry.manifest.id))
    .map((entry) => entry.manifest.id);
  const missingEntries = localEntries.filter((entry) => manifestAdditions.includes(entry.manifest.id));
  if (localEntriesById.size > 0) {
    manifest = {
      ...manifest,
      samples: manifest.samples.map((sample) =>
        localEntriesById.has(sample.id) ? localEntriesById.get(sample.id).manifest : sample,
      ),
    };
  }
  if (missingEntries.length > 0) {
    manifest = {
      ...manifest,
      samples: [...manifest.samples, ...missingEntries.map((entry) => entry.manifest)],
    };
  }

  const allStagedIds = [...new Set([...stagedIds, ...localStagedIds])];
  assertMinimumBundles({ manifest, stagedIds: allStagedIds, degradedReason: null }, minimumBundles);

  if (refreshSnapshot) {
    await writeSnapshot(snapshotPath, manifestUrl, snapshotManifest);
  }

  const result = {
    source: "live",
    degraded: false,
    degradedReason: null,
    manifest,
    stagedIds: allStagedIds,
    stagingRoot,
  };
  await writeStatus(statusPath, result);
  return result;
}

async function readCachedStatus(statusPath) {
  try {
    return JSON.parse(await readFile(statusPath, "utf8"));
  } catch {
    return null;
  }
}

async function finalizeDegraded({ stagingRoot, statusPath, snapshotPath, reason }) {
  console.warn(`sample-bundles: ${reason}`);
  const snapshot = await readSnapshot(snapshotPath);
  // Never trust stale staged files from a previous, different manifest --
  // degraded mode always means "no runnable build this deploy".
  await rm(stagingRoot, { recursive: true, force: true });
  await mkdir(stagingRoot, { recursive: true });
  const result = {
    source: snapshot.manifest ? "snapshot" : "none",
    degraded: true,
    degradedReason: snapshot.manifest
      ? `${reason} (last known-good manifest from ${snapshot.fetchedAt}, built from honua-sdk-js@${describeSnapshotCommit(snapshot.manifest)})`
      : `${reason}; no prior successful fetch is on record either (config/sample-bundles.snapshot.json has never been populated)`,
    manifest: snapshot.manifest,
    stagedIds: [],
    stagingRoot,
  };
  await writeStatus(statusPath, result);
  return result;
}

async function canUseLocalSdkJsRoot(localRoot) {
  if (!localRoot) return null;
  const normalized = path.resolve(localRoot);
  try {
    const entries = await readdir(path.join(normalized, "examples"), { withFileTypes: true });
    return entries.some((entry) => entry.isDirectory()) ? normalized : null;
  } catch {
    return null;
  }
}

async function collectLocalSampleManifestEntries({ localRoot, explicitIds, liveManifest }) {
  if (!localRoot) return [];
  const requestedIds = normalizeLocalIds(explicitIds, liveManifest);
  if (requestedIds.length === 0) return [];

  const packageJson = JSON.parse(await safeReadText(path.join(localRoot, "package.json"), "{}"));
  const packageVersion = packageJson.version ?? null;
  const builtFromCommit = readLocalGitCommit(localRoot);
  const entries = [];
  const seen = new Set();

  for (const id of requestedIds) {
    const distDir = path.join(localRoot, "examples", id, "dist");
    if (!(await pathExists(distDir))) {
      console.warn(`sample-bundles: local override requested for ${id} but no dist directory at ${path.relative(localRoot, distDir)}`);
      continue;
    }
    const files = await collectManifestFiles(distDir);
    if (!files.length) {
      console.warn(`sample-bundles: local override for ${id} is empty at ${path.relative(localRoot, distDir)}; skipping`);
      continue;
    }
    if (seen.has(id)) continue;
    const existingManifest = (liveManifest.samples ?? []).find((sample) => sample.id === id);
    const entrypoint = "index.html";
    entries.push({
      manifest: {
        ...existingManifest,
        id,
        entrypoint,
        dataMode: existingManifest?.dataMode ?? "hybrid",
        configDefaults: existingManifest?.configDefaults ?? {},
        runtimeHosting: existingManifest?.runtimeHosting ?? "self-contained",
        runnability: existingManifest?.runnability ?? "standalone",
        hostFixtureRoutes: existingManifest?.hostFixtureRoutes ?? [],
        support: existingManifest?.support ?? {
          tier: "experimental",
          track: "community",
          validationProfile: "browser-lab",
        },
        lifecycle: {
          ...(existingManifest?.lifecycle ?? {}),
          state: existingManifest?.lifecycle?.state ?? "active",
          reason: existingManifest?.lifecycle?.reason ?? "Locally staged override from sibling honua-sdk-js checkout.",
        },
        builtFrom: {
          commit: builtFromCommit,
          ...(packageVersion ? { packageVersion } : {}),
        },
        files,
      },
      distDir,
    });
    seen.add(id);
  }
  return entries;
}

function normalizeLocalIds(rawIds, liveManifest) {
  if (rawIds) {
    const values = rawIds
      .split(",")
      .map((id) => id.trim())
      .filter(Boolean);
    return [...new Set(values)];
  }
  const excluded = (liveManifest.excluded ?? [])
    .map((entry) => entry?.id)
    .filter((id) => Boolean(id));
  return [...new Set(excluded)];
}

async function collectManifestFiles(distDir) {
  const files = [];
  await collectManifestFilesRecursive(distDir, distDir, files);
  return files;
}

async function collectManifestFilesRecursive(rootDir, currentDir, files) {
  const entries = await readdir(currentDir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(currentDir, entry.name);
    const relPath = path.relative(rootDir, fullPath).replace(/\\/gu, "/");
    if (entry.isDirectory()) {
      await collectManifestFilesRecursive(rootDir, fullPath, files);
      continue;
    }
    if (!entry.isFile()) continue;
    const fileBytes = await readFile(fullPath);
    const sha256 = createHash("sha256").update(fileBytes).digest("hex");
    const integrityDigest = createHash("sha256").update(fileBytes).digest();
    files.push({
      path: relPath,
      bytes: fileBytes.byteLength,
      sha256,
      integrity: `sha256-${integrityDigest.toString("base64")}`,
      mediaType: mediaTypeFromPath(entry.name),
    });
  }
}

async function stageLocalBundles(localEntries, stagingRoot) {
  if (localEntries.length === 0) return [];
  const stagedIds = [];
  for (const { manifest: sample, distDir } of localEntries) {
    const destDir = path.join(stagingRoot, sample.id);
    await rm(destDir, { recursive: true, force: true });
    await mkdir(destDir, { recursive: true });
    await copyDir(distDir, destDir);
    await normalizeLocalBundleEntrypointPaths(path.join(destDir, sample.entrypoint), sample.entrypoint);
    stagedIds.push(sample.id);
  }
  return stagedIds;
}

async function normalizeLocalBundleEntrypointPaths(destEntrypointPath, entrypoint) {
  if (!entrypoint) return;
  try {
    const rawHtml = await readFile(destEntrypointPath, "utf8");
    const rewritten = rawHtml
      .replace(/((?:src|href)=["'])\/assets\//gu, "$1./assets/")
      .replace(/(src|href)="\/__honua-quickstart__\//gu, "$1=\"./__honua-quickstart__/")
      .replace(/(url\()\/__honua-quickstart__\//gu, "$1./__honua-quickstart__/");
    if (rawHtml !== rewritten) {
      await writeFile(destEntrypointPath, rewritten, "utf8");
    }
  } catch {
    // Keep legacy behavior if the local entrypoint is non-HTML or missing.
  }
}

async function pathExists(candidatePath) {
  try {
    await readdir(candidatePath, { withFileTypes: true });
    return true;
  } catch {
    return false;
  }
}

function mediaTypeFromPath(fileName) {
  const extension = path.extname(fileName).toLowerCase();
  if (extension === ".css") return "text/css";
  if (extension === ".html") return "text/html";
  if (extension === ".js") return "text/javascript";
  if (extension === ".json") return "application/json";
  if (extension === ".mjs") return "text/javascript";
  if (extension === ".svg") return "image/svg+xml";
  if (extension === ".png") return "image/png";
  if (extension === ".jpg" || extension === ".jpeg") return "image/jpeg";
  if (extension === ".webp") return "image/webp";
  if (extension === ".gif") return "image/gif";
  if (extension === ".woff2") return "font/woff2";
  return "application/octet-stream";
}

function readLocalGitCommit(localRoot) {
  try {
    return execSync("git rev-parse HEAD", { cwd: localRoot, encoding: "utf8" }).trim();
  } catch {
    return null;
  }
}

async function safeReadText(filePath, fallback = "") {
  try {
    return await readFile(filePath, "utf8");
  } catch {
    return fallback;
  }
}

function describeSnapshotCommit(manifest) {
  const commits = new Set((manifest.samples ?? []).map((s) => s.builtFrom?.commit).filter(Boolean));
  if (commits.size === 0) return "unknown commit";
  if (commits.size === 1) return [...commits][0].slice(0, 12);
  return "mixed commits";
}

async function fetchManifest(manifestUrl) {
  const response = await fetch(manifestUrl);
  if (!response.ok) throw new Error(`HTTP ${response.status} fetching ${manifestUrl}`);
  const manifest = await response.json();
  validateManifestShape(manifest);
  return manifest;
}

function validateManifestShape(manifest) {
  if (manifest?.format !== EXPECTED_FORMAT) {
    throw new Error(`unexpected manifest format ${JSON.stringify(manifest?.format)} (expected "${EXPECTED_FORMAT}")`);
  }
  if (manifest?.schemaVersion !== EXPECTED_SCHEMA_VERSION) {
    throw new Error(
      `unexpected manifest schemaVersion ${JSON.stringify(manifest?.schemaVersion)} (expected ${EXPECTED_SCHEMA_VERSION})`,
    );
  }
  if (!Array.isArray(manifest.samples) || manifest.samples.length === 0) {
    throw new Error("manifest has no samples[]");
  }
  for (const sample of manifest.samples) {
    if (!sample.id || !sample.entrypoint || !Array.isArray(sample.files) || sample.files.length === 0) {
      throw new Error(`manifest sample ${JSON.stringify(sample.id)} is missing required fields`);
    }
  }
}

export { validateManifestShape };

export function parseMinimumBundles(value) {
  if (value === undefined || value === null || String(value).trim() === "") return 0;
  const parsed = Number(value);
  if (!Number.isSafeInteger(parsed) || parsed < 0) {
    throw new Error(`MIN_RUNNABLE_BUNDLES must be a non-negative integer, received ${JSON.stringify(value)}`);
  }
  return parsed;
}

export function assertMinimumBundles(result, minimumBundles) {
  const manifestById = new Map((result.manifest?.samples ?? []).map((sample) => [sample.id, sample]));
  const runnableIds = result.stagedIds.filter((id) => manifestById.get(id)?.runnability === "standalone");
  if (runnableIds.length >= minimumBundles) return;
  const reason = result.degradedReason ? ` ${result.degradedReason}` : "";
  throw new Error(
    `runnable bundle gate requires at least ${minimumBundles} staged standalone bundle(s), found ${runnableIds.length}.${reason}`,
  );
}

async function fetchBytes(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`HTTP ${response.status} fetching ${url}`);
  return Buffer.from(await response.arrayBuffer());
}

/**
 * Extracts the tarball into a scratch directory, verifies every file the
 * manifest declares against its recorded sha256, and only then copies each
 * sample's verified files into `${stagingRoot}/<id>/`. Throws loudly (and
 * stops staging entirely -- no partial/unverified sample is ever left
 * behind) on the first mismatch, missing file, or extra/undeclared file.
 */
async function verifyAndStage({ manifest, tarballBytes, stagingRoot }) {
  const extractDir = await mkdtemp(path.join(os.tmpdir(), "honua-sample-bundles-"));
  const tarballPath = path.join(extractDir, "sample-bundles.tar.gz");
  try {
    await writeFile(tarballPath, tarballBytes);
    await rm(path.join(extractDir, "_out"), { recursive: true, force: true });
    const outDir = path.join(extractDir, "_out");
    await mkdir(outDir, { recursive: true });
    execFileSync("tar", ["-xzf", tarballPath, "-C", outDir], { stdio: ["ignore", "pipe", "pipe"] });

    await rm(stagingRoot, { recursive: true, force: true });
    await mkdir(stagingRoot, { recursive: true });

    const stagedIds = [];
    for (const sample of manifest.samples) {
      await verifySampleFiles(path.join(outDir, sample.id), sample);
      const destDir = path.join(stagingRoot, sample.id);
      await mkdir(destDir, { recursive: true });
      await copyDir(path.join(outDir, sample.id), destDir);
      stagedIds.push(sample.id);
    }
    return stagedIds;
  } finally {
    await rm(extractDir, { recursive: true, force: true });
  }
}

/**
 * Re-hashes every file `sampleManifest.files` declares against the bytes
 * actually extracted under `sampleDir`, throwing with a specific path/hash
 * on the first mismatch. Exported so verification can be exercised directly
 * (real extraction dir in, real manifest in) without touching the network --
 * used by this repo's own integrity-check demo and available for tests.
 */
export async function verifySampleFiles(sampleDir, sampleManifest) {
  for (const file of sampleManifest.files) {
    const filePath = path.join(sampleDir, file.path);
    let bytes;
    try {
      bytes = await readFile(filePath);
    } catch (err) {
      throw new Error(
        `sample-bundles: ${sampleManifest.id}: manifest declares "${file.path}" but it is missing from the extracted tarball (${err.message})`,
      );
    }
    if (bytes.byteLength !== file.bytes) {
      throw new Error(
        `sample-bundles: ${sampleManifest.id}: "${file.path}" is ${bytes.byteLength} bytes, manifest declares ${file.bytes}`,
      );
    }
    const actualSha256 = createHash("sha256").update(bytes).digest("hex");
    if (actualSha256 !== file.sha256) {
      throw new Error(
        `sample-bundles: INTEGRITY MISMATCH: ${sampleManifest.id}: "${file.path}" sha256 is ${actualSha256}, manifest declares ${file.sha256} -- refusing to stage`,
      );
    }
  }
}

async function copyDir(srcDir, destDir) {
  const entries = await readdir(srcDir, { withFileTypes: true });
  for (const entry of entries) {
    const src = path.join(srcDir, entry.name);
    const dest = path.join(destDir, entry.name);
    if (entry.isDirectory()) {
      await mkdir(dest, { recursive: true });
      await copyDir(src, dest);
    } else if (entry.isFile()) {
      await writeFile(dest, await readFile(src));
    }
  }
}

async function readSnapshot(snapshotPath) {
  try {
    const raw = JSON.parse(await readFile(snapshotPath, "utf8"));
    return { manifest: raw.manifest ?? null, fetchedAt: raw.fetchedAt ?? null, sourceUrl: raw.sourceUrl ?? null };
  } catch {
    return { manifest: null, fetchedAt: null, sourceUrl: null };
  }
}

async function writeSnapshot(snapshotPath, sourceUrl, manifest) {
  const snapshot = {
    _comment:
      "Committed fallback snapshot consumed by scripts/lib/sample-bundles.mjs (via scripts/build-gallery.mjs / " +
      "the pages.yml staging step) when the live fetch of honua-sdk-js's sample-bundles-latest release fails, " +
      "so a samples.honua.io deploy degrades to an honest \"no runnable build published yet\" for every sdk-js " +
      "sample rather than breaking the deploy. Only manifest metadata is recorded here -- the actual bundle " +
      "*files* (~8MB+ of built JS/CSS/wasm) are never committed, so a degraded deploy never serves stale or " +
      "unverified bytes, only the honest no-bundle panel plus this record's builtFrom provenance in the notice. " +
      "Rewritten automatically whenever a live fetch + full integrity verification succeeds -- commit the change " +
      "to keep the offline record current. See honua-io/honua-samples#11.",
    sourceUrl,
    fetchedAt: new Date().toISOString(),
    manifest,
  };
  await mkdir(path.dirname(snapshotPath), { recursive: true });
  await writeFile(snapshotPath, JSON.stringify(snapshot, null, 2) + "\n", "utf8");
}

async function writeStatus(statusPath, result) {
  await mkdir(path.dirname(statusPath), { recursive: true });
  await writeFile(statusPath, JSON.stringify(result, null, 2) + "\n", "utf8");
}

// ---- CLI entry point (pages.yml's dedicated staging step) ----------------

const isMain = (() => {
  try {
    return process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
  } catch {
    return false;
  }
})();

if (isMain) {
  ensureSampleBundlesStaged({ forceRefetch: true })
    .then(async (result) => {
      if (result.degraded) {
        console.warn(`sample-bundles: DEGRADED -- ${result.degradedReason}`);
        console.warn("sample-bundles: no bundles staged this run; the gallery will show \"no runnable build published yet\" for every sdk-js entry.");
        return; // exit 0: a fetch failure never fails the deploy.
      }
      console.log(
        `sample-bundles: staged ${result.stagedIds.length} verified sample bundle(s) to ${path.relative(REPO_ROOT, result.stagingRoot)}: ${result.stagedIds.join(", ")}`,
      );
    })
    .catch((err) => {
      console.error(`sample-bundles: ${err.message}`);
      process.exitCode = 1; // integrity/manifest-shape failures fail the deploy.
    });
}
